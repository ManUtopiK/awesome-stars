#!/usr/bin/env python3
"""Generate README.md and topics.md from the GitHub stars of a user."""

import http.client
import json
import os
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

API_URL = 'https://api.github.com/graphql'
# GitHub answers 502 when a page takes about 10 s to build: 100 repositories is too many.
PAGE_SIZE = 30
REQUEST_TIMEOUT = 30
MAX_ATTEMPTS = 8
BASE_DELAY = 5
MAX_DELAY = 300
RATE_LIMIT_MIN_DELAY = 60
TOPIC_MIN_STARS = 500
DESCRIPTION_LIMIT = 200

QUERY = '''
query ($username: String!, $first: Int!, $after: String) {
  user(login: $username) {
    starredRepositories(first: $first, after: $after, orderBy: {direction: DESC, field: STARRED_AT}) {
      nodes {
        nameWithOwner
        description
        url
        isPrivate
        languages(first: 1, orderBy: {field: SIZE, direction: DESC}) {
          edges { node { name } }
        }
        repositoryTopics(first: 100) {
          nodes { topic { name stargazerCount } }
        }
      }
      pageInfo { endCursor hasNextPage }
    }
  }
}
'''

HEADER = '''<!--lint disable awesome-contributing awesome-license awesome-list-item match-punctuation no-repeat-punctuation no-undefined-references awesome-spell-check-->
# Awesome Stars [![Awesome](https://awesome.re/badge.svg)](https://github.com/sindresorhus/awesome)

> A curated list of my GitHub stars! Generated by [starred](https://github.com/maguowei/starred).

## Contents

'''

LICENSE = '''
## License

[![CC0](http://mirrors.creativecommons.org/presskit/buttons/88x31/svg/cc-zero.svg)](https://creativecommons.org/publicdomain/zero/1.0/)

To the extent possible under law, [{username}](https://github.com/{username}) has waived all copyright and related or neighboring rights to this work.

'''


class FetchError(Exception):
    """The stars could not be fetched; nothing must be published."""


class _Transient(Exception):
    def __init__(self, message, retry_after=None, min_delay=0):
        super().__init__(message)
        self.retry_after = retry_after
        self.min_delay = min_delay


def _read_page(post, variables):
    try:
        status, headers, body = post(variables)
    except (OSError, http.client.HTTPException) as error:
        raise _Transient(repr(error)) from error

    if status in (403, 429):
        retry_after = headers.get('Retry-After')
        raise _Transient(
            f'HTTP {status}',
            retry_after=int(retry_after) if retry_after else None,
            min_delay=RATE_LIMIT_MIN_DELAY,
        )
    if status >= 500:
        raise _Transient(f'HTTP {status}')
    if status != 200:
        raise FetchError(f'HTTP {status}: {body[:200]!r}')

    try:
        payload = json.loads(body)
    except ValueError as error:
        raise _Transient(f'invalid JSON: {body[:200]!r}') from error
    if payload.get('errors') or not payload.get('data'):
        raise _Transient(f"GraphQL errors: {payload.get('errors')}")
    return payload['data']['user']['starredRepositories']


def _read_page_with_retries(post, variables, sleep):
    for attempt in range(MAX_ATTEMPTS):
        try:
            return _read_page(post, variables)
        except _Transient as error:
            if attempt == MAX_ATTEMPTS - 1:
                raise FetchError(f'giving up after {MAX_ATTEMPTS} attempts: {error}') from error
            delay = error.retry_after
            if delay is None:
                delay = max(error.min_delay, min(BASE_DELAY * 2**attempt, MAX_DELAY))
            print(f'{error}, retrying in {delay} s', file=sys.stderr, flush=True)
            sleep(delay)


def fetch_stars(username, post, sleep=time.sleep):
    nodes = []
    after = None
    while True:
        variables = {'username': username, 'first': PAGE_SIZE, 'after': after}
        stars = _read_page_with_retries(post, variables, sleep)
        nodes.extend(stars['nodes'])
        if not stars['pageInfo']['hasNextPage']:
            return nodes
        after = stars['pageInfo']['endCursor']
        if len(nodes) % 1500 == 0:
            print(f'{len(nodes)} stars fetched', file=sys.stderr, flush=True)


def github_post(token):
    headers = {
        'Authorization': f'Bearer {token}',
        'Content-Type': 'application/json',
        'User-Agent': 'awesome-stars',
    }

    def post(variables):
        data = json.dumps({'query': QUERY, 'variables': variables}).encode()
        request = urllib.request.Request(API_URL, data=data, headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=REQUEST_TIMEOUT) as response:
                return response.status, response.headers, response.read()
        except urllib.error.HTTPError as error:
            return error.code, error.headers, error.read()

    return post


def _language(node):
    edges = node['languages']['edges']
    return edges[0]['node']['name'] if edges else None


def _topics(node):
    return [
        item['topic']['name']
        for item in node['repositoryTopics']['nodes']
        if item['topic']['stargazerCount'] > TOPIC_MIN_STARS
    ]


def _description(node):
    text = (node['description'] or '').replace('>', '&gt;').replace('<', '&lt;')
    return text.replace('\n', '').strip()[:DESCRIPTION_LIMIT]


def render(nodes, username, by_topic=False):
    groups = {}
    for node in nodes:
        if node['isPrivate']:
            continue
        categories = (_topics(node) or ['others']) if by_topic else [_language(node) or 'Others']
        entry = f"- [{node['nameWithOwner']}]({node['url']}) - {_description(node)}\n"
        for category in categories:
            groups.setdefault(category, []).append(entry)

    lines = [HEADER]
    categories = sorted(groups)
    for category in categories:
        anchor = '-'.join(category.lower().split())
        lines.append(f'- [{category}](#{anchor})\n')
    lines.append('\n')
    for category in categories:
        lines.append('## {} \n\n'.format(category.replace('#', '# #')))
        lines.extend(groups[category])
        lines.append('\n')
    lines.append(LICENSE.format(username=username))
    return ''.join(lines).encode()


def update(username, post, directory, sleep=time.sleep):
    nodes = fetch_stars(username, post, sleep)
    print(f'{len(nodes)} stars fetched in total', file=sys.stderr, flush=True)
    (directory / 'README.md').write_bytes(render(nodes, username))
    (directory / 'topics.md').write_bytes(render(nodes, username, by_topic=True))


def main():
    directory = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
    try:
        update(os.environ['STARS_USER'], github_post(os.environ['GITHUB_TOKEN']), directory)
    except FetchError as error:
        sys.exit(f'Error: {error}')


if __name__ == '__main__':
    main()
